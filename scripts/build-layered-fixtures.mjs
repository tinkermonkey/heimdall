#!/usr/bin/env node
// Builds the layered-graph test fixtures from Documentation Robotics data, as plain GraphCanvas
// nodes and edges with a `layer` attribute (the layered views' input model):
//
//   - drSpec:      the DR spec meta-model, one node per node type, one edge per relationship
//                  schema (label = predicate, attributes.category = the predicate's category)
//   - heimdallUx:  this repo's own DR model (documentation-robotics/model), one node per element
//
// Writes src/test-pages/fixtures/layeredGraphFixtures.ts. Test data only: the library itself
// knows nothing about DR.
//
// With --full it writes src/test-pages/fixtures/layeredGraphFullSpec.ts instead: the whole spec
// meta-model (every layer in the spec manifest), compact (tuples, no descriptions), for the
// scale and performance checks.
//
// Usage:
//   node scripts/build-layered-fixtures.mjs [--spec <documentation_robotics/spec dir>]
//                                           [--layers business,application,technology] [--full]
// --spec defaults to ../documentation_robotics/spec next to the repo root.

import { readFile, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const arg = (name, fallback) => {
  const i = process.argv.indexOf(name)
  return i >= 0 ? process.argv[i + 1] : fallback
}
const specDir = path.resolve(arg('--spec', path.join(ROOT, '..', 'documentation_robotics', 'spec')))
const layers = arg('--layers', 'business,application,technology').split(',')
const modelDir = path.join(ROOT, 'documentation-robotics', 'model')
const OUT = path.join(ROOT, 'src', 'test-pages', 'fixtures', 'layeredGraphFixtures.ts')

const readJson = async (p) => JSON.parse(await readFile(p, 'utf8'))
const firstSentence = (s = '', max = 170) => {
  const one = s.split('. ')[0]
  return one.length > max ? one.slice(0, max).replace(/\s+\S*$/, '') + '…' : one
}

let yaml
try {
  yaml = (await import('js-yaml')).default
} catch {
  console.error('js-yaml is needed to read the heimdall-ux model (it ships with the dev dependencies).')
  process.exit(1)
}

// ---- predicate categories (spec base.json)
const base = await readJson(path.join(specDir, 'dist', 'base.json'))
const categoryOf = Object.fromEntries(Object.entries(base.predicates).map(([p, v]) => [p, v.category]))

// ---- --full: every layer of the spec, compact
if (process.argv.includes('--full')) {
  const manifest = await readJson(path.join(specDir, 'dist', 'manifest.json'))
  const fullLayers = manifest.layers.map((l) => ({ id: l.id, label: l.name.replace(/ Layer$/, '') }))
  const nodes = [] // [layer index, type, title]
  const index = new Map()
  for (const [li, l] of fullLayers.entries()) {
    const dist = await readJson(path.join(specDir, 'dist', `${l.id}.json`))
    for (const [type, schema] of Object.entries(dist.nodeSchemas)) {
      index.set(`${l.id}.${type}`, nodes.length)
      nodes.push([li, type, schema.title ?? type])
    }
  }
  const predicates = []
  const edges = [] // [source index, target index, predicate index]
  for (const l of fullLayers) {
    const dist = await readJson(path.join(specDir, 'dist', `${l.id}.json`))
    for (const rel of Object.values(dist.relationshipSchemas)) {
      const p = rel.properties ?? rel
      const s = index.get(p.source_spec_node_id?.const ?? rel.source_spec_node_id)
      const t = index.get(p.destination_spec_node_id?.const ?? rel.destination_spec_node_id)
      const predicate = p.predicate?.const ?? rel.predicate
      if (s === undefined || t === undefined) continue
      if (!predicates.includes(predicate)) predicates.push(predicate)
      edges.push([s, t, predicates.indexOf(predicate)])
    }
  }
  const FULL_OUT = path.join(ROOT, 'src', 'test-pages', 'fixtures', 'layeredGraphFullSpec.ts')
  const rows = (list) => list.map((r) => JSON.stringify(r)).join(',\n')
  await writeFile(
    FULL_OUT,
    `// Generated by scripts/build-layered-fixtures.mjs --full from Documentation Robotics data (MIT). Do not edit.
// Spec ${manifest.specVersion}: ${fullLayers.length} layers, ${nodes.length} node types, ${edges.length} relationship schemas.
import type { GraphEdge, GraphNodeData } from '../../components/GraphCanvas'

/** Layer order and labels, top to bottom (layerBy: 'layer'). */
export const drFullLayers = ${JSON.stringify(fullLayers)}

const predicates: string[] = ${JSON.stringify(predicates)}
const categories: Record<string, string> = ${JSON.stringify(Object.fromEntries(predicates.map((p) => [p, categoryOf[p] ?? 'other'])))}
/** [layer index, type, title] */
const N: [number, string, string][] = [
${rows(nodes)},
]
/** [source, target, predicate] as indices */
const E: [number, number, number][] = [
${rows(edges)},
]

/** The whole DR spec meta-model: one node per node type, one edge per relationship schema. */
export const drFullNodes: GraphNodeData[] = N.map(([li, type, title]) => ({
  id: \`\${drFullLayers[li].id}.\${type}\`,
  label: title,
  kind: type,
  attributes: { layer: drFullLayers[li].id },
}))
export const drFullEdges: GraphEdge[] = E.map(([s, t, p], i) => ({
  id: \`r\${i}\`,
  sourceId: drFullNodes[s].id,
  targetId: drFullNodes[t].id,
  label: predicates[p],
  attributes: { category: categories[predicates[p]] },
}))
`,
  )
  console.log(`wrote ${path.relative(ROOT, FULL_OUT)}: ${fullLayers.length} layers, ${nodes.length} nodes / ${edges.length} edges`)
  process.exit(0)
}

// ---- DR spec meta-model
const specNodes = []
const specEdges = []
const specIds = new Set()
for (const layer of layers) {
  const dist = await readJson(path.join(specDir, 'dist', `${layer}.json`))
  for (const [type, schema] of Object.entries(dist.nodeSchemas)) {
    const id = `${layer}.${type}`
    specIds.add(id)
    specNodes.push({ id, label: schema.title ?? type, kind: type, attributes: { layer, description: firstSentence(schema.description) } })
  }
}
for (const layer of layers) {
  const dist = await readJson(path.join(specDir, 'dist', `${layer}.json`))
  for (const [id, rel] of Object.entries(dist.relationshipSchemas)) {
    const p = rel.properties ?? rel
    const s = p.source_spec_node_id?.const ?? rel.source_spec_node_id
    const t = p.destination_spec_node_id?.const ?? rel.destination_spec_node_id
    const predicate = p.predicate?.const ?? rel.predicate
    if (!specIds.has(s) || !specIds.has(t)) continue
    specEdges.push({ id, sourceId: s, targetId: t, label: predicate, attributes: { category: categoryOf[predicate] ?? 'other' } })
  }
}

// ---- heimdall-ux model (this repo's own DR model)
const uxNodes = []
const uxEdges = []
const dirs = (await readdir(modelDir, { withFileTypes: true })).filter((d) => d.isDirectory())
for (const d of dirs) {
  for (const f of await readdir(path.join(modelDir, d.name))) {
    if (!f.endsWith('.yaml')) continue
    const doc = yaml.load(await readFile(path.join(modelDir, d.name, f), 'utf8')) ?? {}
    for (const [id, el] of Object.entries(doc)) {
      if (!layers.includes(el.layer_id)) continue
      uxNodes.push({ id, label: el.name, kind: el.type, attributes: { layer: el.layer_id, description: firstSentence(el.description) } })
    }
  }
}
const uxIds = new Set(uxNodes.map((n) => n.id))
const rels = yaml.load(await readFile(path.join(modelDir, 'relationships.yaml'), 'utf8')) ?? []
rels.forEach((r, i) => {
  if (!uxIds.has(r.source) || !uxIds.has(r.target)) return
  uxEdges.push({ id: `rel-${i}`, sourceId: r.source, targetId: r.target, label: r.predicate, attributes: { category: categoryOf[r.predicate] ?? 'other' } })
})

const json = (v) => JSON.stringify(v, null, 1)
const out = `// Generated by scripts/build-layered-fixtures.mjs from Documentation Robotics data (MIT). Do not edit.
// Spec ${base.specVersion ?? ''}, layers: ${layers.join(', ')}.
import type { GraphEdge, GraphNodeData } from '../../components/GraphCanvas'

/** Layer order and labels for both fixtures (layerBy: 'layer'). */
export const drLayers = ${json(layers.map((id) => ({ id, label: id[0].toUpperCase() + id.slice(1) })))}

/** Category order that reproduces the prototype styling: structural solid, behavioral dashed, dependency dotted. */
export const drCategoryOrder = ['structural', 'behavioral', 'dependency']

/** DR spec meta-model: ${specNodes.length} node types, ${specEdges.length} relationship schemas. */
export const drSpecNodes: GraphNodeData[] = ${json(specNodes)}
export const drSpecEdges: GraphEdge[] = ${json(specEdges)}

/** heimdall-ux model: ${uxNodes.length} elements, ${uxEdges.length} relationships. */
export const heimdallUxNodes: GraphNodeData[] = ${json(uxNodes)}
export const heimdallUxEdges: GraphEdge[] = ${json(uxEdges)}
`
await writeFile(OUT, out)
console.log(`wrote ${path.relative(ROOT, OUT)}: drSpec ${specNodes.length} nodes / ${specEdges.length} edges, heimdallUx ${uxNodes.length} nodes / ${uxEdges.length} edges`)
